/**
 * 演示沙箱的**开关**（内存态，唯一一处真相）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么是内存态而不是磁盘上的一个标记文件
 * ══════════════════════════════════════════════════════════════════════════
 * 学生态被整个换掉这件事**只在本次运行里有意义**：关掉应用再打开就该回到真实数据。
 * 写成磁盘标记会制造两种新的坏情况：
 *   · 演示完忘了关 → 下次打开还是一屏预置内容，而**界面上没有任何指示**（无痕口径的另一面）；
 *   · 真数据"不见了" → 学生以为自己的记录丢了（其实只是被盖住了）。
 * 所以：**进程一退出就自动回到普通态**，不需要任何清理动作。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 它被谁读（三处，缺一处就会出现"半沙箱"）
 * ══════════════════════════════════════════════════════════════════════════
 *   ① `bridge/client.ts` 的 `apiFetch` —— 覆盖层在这里拦下学生态读请求；
 *   ② `ipc/handlers.ts` 的四个处理器 —— 沙箱分支必须早于 `ensureChatRuntime()`；
 *   ③ 写操作的拒绝分支 —— 在 IPC 处理器层回一句可读中文。
 *
 * ⚠️ 本文件只在主进程加载，但**不碰任何 Node 内建模块**（它是纯布尔状态）——
 *   这样 `tests/demo-seed.test.ts` 能直接 import 它做断言，不必起 Electron。
 */

import type { DemoSeedState } from '@shared/demo-seed'

/**
 * 当前是否处于沙箱态。
 *
 * ★ 用模块级变量而不是 `app.getPath` / 配置对象：它就是一次运行期内的一比特，
 *   没有第二处真相，也就不存在"两处不一致"的可能。
 */
let seeded = false

/** 现在是不是沙箱态（覆盖层与处理器每次都问这一句）。 */
export function isDemoSeeded(): boolean {
  return seeded
}

/** 对外的状态值（`demo:state` 回执与 `demo:seed` 入参用的是同一个枚举）。 */
export function demoSeedState(): DemoSeedState {
  return seeded ? 'seeded' : 'inactive'
}

/**
 * 切到指定档位，返回**是否真的变了**。
 *
 * ★ 返回值就是"要不要重载界面"的判据：值没变时调用方直接回执、**不重载**
 *   （否则连点两次按钮会把界面刷两遍，而学生看到的是"点了没反应但界面在闪"）。
 */
export function setDemoSeeded(next: DemoSeedState): boolean {
  const wanted = next === 'seeded'
  if (wanted === seeded) return false
  seeded = wanted
  return true
}

/**
 * 测试专用：复位到普通态。
 *
 * ★ 生产路径**没有**这个调用 —— 复位只能靠"关掉应用"（见文件头第一条理由）。
 *   单测要跑多轮时必须能复位，否则第一个用例进沙箱、后面全在沙箱里跑。
 */
export function resetDemoSeedForTests(): void {
  seeded = false
}
