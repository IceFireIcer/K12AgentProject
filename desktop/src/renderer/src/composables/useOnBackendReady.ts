/**
 * 「后端就绪后再跑一次」——首屏取数的**统一重试机制**。
 *
 * ── 要解决的那件事（打包版冷启动实测踩到）────────────────────────────────
 * sidecar 是**独立的 Python 进程**，从启动到能应答要几秒；而渲染进程一挂载
 * 就会发首屏那批请求（侧栏昵称、模型 chip、右栏画像…）。
 * 于是**冷启动几乎必然先撞一次「sidecar 尚未就绪」**。
 *
 * 只发一次的话，那几个失败会**就地定格**：顶栏永远写「未配置模型」、
 * 右栏永远挂着「读取失败：sidecar 尚未就绪」—— 而服务其实几秒后就好了。
 * 学生看到的是「这软件坏了」，实际只是**没人去重试**。
 *
 * ── 为什么触发信号取「phase 变成 ready」──────────────────────────────────
 * 那就是「后端可用了」的**权威信号**，比定时轮询准确，也不用猜要等多久
 * （冷机可能 3 秒、装了杀毒软件的机器可能 10 秒）。
 *
 * ── 用法 ────────────────────────────────────────────────────────────────
 * ```ts
 * useOnBackendReady(() => {
 *   void student.load()
 *   void settings.load()
 * })
 * ```
 * **调用方负责幂等**：这个组合式函数会先立刻跑一次、再在就绪后跑一次，
 * 所以 `run` 必须能安全地重复调用（本项目里这些 `load()` 都带
 * 「已有数据就返回」的短路，正合这条要求）。重试也**不会**覆盖用户输入 ——
 * 它们只写自己那份快照，不碰界面上的草稿。
 */

import { onUnmounted, watch } from 'vue'
import { useSidecarStore } from '../stores/sidecar'

export function useOnBackendReady(run: () => void): void {
  const sidecar = useSidecarStore()

  // 立刻跑一次：多数情况下（开发态、二次启动）sidecar 已经在跑，这一次就成。
  // ⚠️ 这里是**同步执行**而不是包在 `onMounted` 里 —— 有意为之：
  //   数据越早请求越早回来，而 `run` 只发起请求、不读 DOM，挂载前跑是安全的。
  run()

  // 再挂一个「就绪时补跑」的看门人。`phase` 是状态机的输出，
  // 所以不必去抖：正常只在 idle → starting → ready 之间跳几次。
  const stop = watch(
    () => sidecar.phase,
    (phase) => {
      if (phase === 'ready') run()
    }
  )

  // 组件卸载时停掉（`watch` 在组件作用域里本来会自动停，
  // 但本函数也可能在非组件上下文里被调用 —— 显式停一次不吃亏）。
  onUnmounted(stop)
}
